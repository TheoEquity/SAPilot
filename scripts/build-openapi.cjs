#!/usr/bin/env node
'use strict';

// Shared metadata + one Paths Object fragment per HTTP operation.
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { createRequire } = require('node:module');
const { isDeepStrictEqual } = require('node:util');

const repository = path.resolve(__dirname, '..');
const webRequire = createRequire(path.join(repository, 'web', 'package.json'));
const YAML = webRequire('yaml');
const { bundle, createConfig, stringifyYaml } = webRequire('@redocly/openapi-core');
const methods = new Set(['get', 'post', 'put', 'patch', 'delete', 'head', 'options', 'trace']);
const pathFields = new Set(['parameters', 'summary', 'description', 'servers']);
const generatedHeader = '# Generated by scripts/build-openapi.cjs. Do not edit.\n';

function options(argv) {
  const result = {
    source: path.join(repository, 'aperag', 'api'),
    output: path.join(repository, '.run', 'openapi'),
    modules: [],
  };
  for (let i = 0; i < argv.length; i++) {
    const flag = argv[i];
    if (flag === '--help') {
      process.stdout.write('Usage: node scripts/build-openapi.cjs [--source DIR] [--output DIR] [--module NAME ...]\n');
      return null;
    }
    if (!['--source', '--output', '--module'].includes(flag) || !argv[i + 1] || argv[i + 1].startsWith('--')) {
      throw new Error(`Invalid argument: ${flag}`);
    }
    const value = argv[++i];
    if (flag === '--module') result.modules.push(value);
    else result[flag.slice(2)] = path.resolve(value);
  }
  return result;
}

function sourceReader(source) {
  const cache = new Map();
  function read(file) {
    file = path.resolve(file);
    if (!cache.has(file)) {
      const relative = path.relative(source, file);
      if (relative.startsWith(`..${path.sep}`) || relative === '..' || path.isAbsolute(relative)) {
        throw new Error(`Reference leaves the API source directory: ${file}`);
      }
      const document = YAML.parseDocument(fs.readFileSync(file, 'utf8'), { uniqueKeys: true });
      if (document.errors.length) throw new Error(`${file}: ${document.errors[0].message}`);
      cache.set(file, document.toJSON());
    }
    return cache.get(file);
  }
  function reference(ref, origin) {
    if (typeof ref !== 'string' || /^[a-z][a-z0-9+.-]*:/i.test(ref)) {
      throw new Error(`Expected a local reference in ${origin}: ${ref}`);
    }
    const hash = ref.indexOf('#');
    const filePart = hash < 0 ? ref : ref.slice(0, hash);
    const fragment = hash < 0 ? '' : ref.slice(hash + 1);
    const file = filePart ? path.resolve(path.dirname(origin), decodeURIComponent(filePart)) : origin;
    let value = read(file);
    if (fragment && !fragment.startsWith('/')) throw new Error(`Expected a JSON Pointer in ${origin}: ${ref}`);
    if (fragment) {
      for (const token of fragment.slice(1).split('/')) {
        const key = decodeURIComponent(token).replace(/~1/g, '/').replace(/~0/g, '~');
        if (value === null || typeof value !== 'object' || !Object.hasOwn(value, key)) {
          throw new Error(`Unresolved reference in ${origin}: ${ref}`);
        }
        value = value[key];
      }
    }
    return { file, fragment, value };
  }
  const visited = new Set();
  function validate(value, origin) {
    if (!value || typeof value !== 'object') return;
    if (!Array.isArray(value) && Object.hasOwn(value, '$ref')) {
      const ref = reference(value.$ref, origin);
      const key = `${ref.file}#${ref.fragment}`;
      if (!visited.has(key)) {
        visited.add(key);
        validate(ref.value, ref.file);
      }
    }
    for (const child of Object.values(value)) validate(child, origin);
  }
  function rebase(value, origin, destination) {
    if (Array.isArray(value)) return value.map(item => rebase(item, origin, destination));
    if (!value || typeof value !== 'object') return value;
    return Object.fromEntries(Object.entries(value).map(([key, child]) => {
      if (key !== '$ref') return [key, rebase(child, origin, destination)];
      const ref = reference(child, origin);
      const relative = path.relative(path.dirname(destination), ref.file).split(path.sep).join('/');
      return [key, `${relative}${ref.fragment ? `#${ref.fragment}` : ''}`];
    }));
  }
  return { read, validate, rebase };
}

function filesBelow(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name, 'en')).flatMap(entry => {
    const file = path.join(directory, entry.name);
    if (entry.isDirectory()) return filesBelow(file);
    return entry.isFile() && /\.ya?ml$/i.test(entry.name) ? [file] : [];
  });
}

function safeOutput(source, output, names = []) {
  function realPath(file) {
    try {
      return fs.realpathSync(file);
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
      return path.join(realPath(path.dirname(file)), path.basename(file));
    }
  }
  const realSource = fs.realpathSync(source);
  for (const target of [output, ...names.map(name => path.join(output, name))]) {
    const relative = path.relative(realSource, realPath(target));
    if (!relative || (!relative.startsWith(`..${path.sep}`) && relative !== '..' && !path.isAbsolute(relative))) {
      throw new Error('Generated output must be outside the API source directory');
    }
    // Reject redirects within the output tree, including existing artifact files.
    for (let current = target; ; current = path.dirname(current)) {
      try {
        if (fs.lstatSync(current).isSymbolicLink()) throw new Error(`Output contains a symbolic link: ${current}`);
      } catch (error) {
        if (error.code !== 'ENOENT') throw error;
      }
      if (current === output) break;
    }
  }
}

async function buildOpenApi(settings) {
  const source = path.resolve(settings.source);
  const output = path.resolve(settings.output);
  safeOutput(source, output);
  const reader = sourceReader(source);
  const metadataFile = path.join(source, 'openapi.yaml');
  const metadata = reader.read(metadataFile);
  if (!metadata?.openapi || !metadata?.info || Object.hasOwn(metadata, 'paths')) {
    throw new Error('openapi.yaml must contain shared OpenAPI metadata, without a paths registry');
  }
  reader.validate(metadata, metadataFile);
  const routes = new Set();
  const routeNames = new Map();
  const operations = [];
  const pathDirectory = path.join(source, 'paths');
  for (const file of filesBelow(pathDirectory)) {
    const relative = path.relative(pathDirectory, file).split(path.sep);
    if (relative.length < 2 || !/^[a-z][a-z0-9_-]*$/.test(relative[0])) {
      throw new Error(`Place each operation under paths/<module>/<name>.yaml: ${file}`);
    }
    const fragment = reader.read(file);
    const paths = fragment && typeof fragment === 'object' ? Object.keys(fragment) : [];
    if (paths.length !== 1 || !paths[0].startsWith('/')) throw new Error(`Expected one path in ${file}`);
    const route = paths[0];
    const item = fragment[route];
    const keys = item && typeof item === 'object' ? Object.keys(item) : [];
    const verbs = keys.filter(key => methods.has(key));
    if (verbs.length !== 1 || keys.some(key => !methods.has(key) && !pathFields.has(key) && !key.startsWith('x-'))) {
      throw new Error(`Expected one HTTP operation in ${file}`);
    }
    const method = verbs[0];
    const template = route.replace(/\{[^}]+\}/g, '{}');
    if (routeNames.has(template) && routeNames.get(template) !== route) {
      throw new Error(`Conflicting templated paths: ${routeNames.get(template)} and ${route}`);
    }
    routeNames.set(template, route);
    const identity = `${method} ${route}`;
    if (routes.has(identity)) throw new Error(`Duplicate operation: ${identity}`);
    routes.add(identity);
    reader.validate(item, file);
    operations.push({ file, module: relative[0], route, method, item });
  }
  if (!operations.length) throw new Error('No independent HTTP operation files found');
  const modules = [...new Set(operations.map(operation => operation.module))].sort();
  const selected = [...new Set(settings.modules)].sort();
  for (const module of selected) {
    if (!modules.includes(module)) throw new Error(`Unknown module: ${module}`);
  }
  const outputs = selected.length
    ? selected.map(module => ({ name: `modules/${module}.yaml`, operations: operations.filter(op => op.module === module) }))
    : [
      { name: 'openapi.yaml', operations },
      ...modules.map(module => ({ name: `modules/${module}.yaml`, operations: operations.filter(op => op.module === module) })),
    ];
  const staging = fs.mkdtempSync(path.join(os.tmpdir(), 'sapilot-openapi-'));
  const stagedFiles = [];
  const results = [];
  try {
    const config = await createConfig({});
    for (let i = 0; i < outputs.length; i++) {
      const spec = outputs[i];
      const entry = path.join(staging, `${i}.yaml`);
      const document = { ...reader.rebase(metadata, metadataFile, entry), paths: {} };
      const ids = new Set();
      for (const operation of spec.operations) {
        const id = operation.item[operation.method].operationId;
        if (id && ids.has(id)) throw new Error(`Duplicate operationId in ${spec.name}: ${id}`);
        if (id) ids.add(id);
        const item = reader.rebase(operation.item, operation.file, entry);
        const target = document.paths[operation.route] ||= {};
        for (const [key, value] of Object.entries(item)) {
          if (Object.hasOwn(target, key) && !isDeepStrictEqual(target[key], value)) {
            throw new Error(`Conflicting path field ${key} for ${operation.route}`);
          }
          target[key] = value;
        }
      }
      fs.writeFileSync(entry, stringifyYaml(document), 'utf8');
      stagedFiles.push(entry);
      const result = await bundle({ ref: entry, config });
      const failures = result.problems.filter(problem => problem.severity === 'error');
      if (failures.length) throw new Error(failures.map(problem => problem.message).join('\n'));
      results.push({ name: spec.name, content: generatedHeader + stringifyYaml(result.bundle.parsed) });
    }
    // Validation and all bundles finish before any published artifact is changed.
    safeOutput(source, output, results.map(result => result.name));
    for (const result of results) {
      const destination = path.join(output, result.name);
      fs.mkdirSync(path.dirname(destination), { recursive: true });
      fs.writeFileSync(destination, result.content, 'utf8');
    }
    if (!selected.length) {
      const moduleDirectory = path.join(output, 'modules');
      const active = new Set(results.map(result => path.join(output, result.name)));
      for (const name of fs.readdirSync(moduleDirectory)) {
        const file = path.join(moduleDirectory, name);
        if (/\.yaml$/.test(name) && !active.has(file) && fs.statSync(file).isFile()
            && fs.readFileSync(file, 'utf8').startsWith(generatedHeader)) fs.unlinkSync(file);
      }
    }
    const operationCount = selected.length ? operations.filter(operation => selected.includes(operation.module)).length : operations.length;
    return { operations: operationCount, modules: selected.length ? selected : modules, outputs: results.map(result => path.join(output, result.name)) };
  } finally {
    // Only remove files created by this invocation; never recursively delete a tree.
    for (const file of stagedFiles) fs.unlinkSync(file);
    fs.rmdirSync(staging);
  }
}

if (require.main === module) {
  (async () => {
    const settings = options(process.argv.slice(2));
    if (settings) process.stdout.write(`${JSON.stringify(await buildOpenApi(settings), null, 2)}\n`);
  })().catch(error => {
    process.stderr.write(`OpenAPI build failed: ${error.message}\n`);
    process.exitCode = 1;
  });
}

module.exports = { buildOpenApi };
